/** JSON with object keys sorted at every level, so equal states always serialise identically (ADR-003). */
export function canonicalJson(value: unknown): string {
  return JSON.stringify(sortKeys(value));
}

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value !== null && typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(value).sort()) {
      const v = (value as Record<string, unknown>)[key];
      if (v !== undefined) out[key] = sortKeys(v);
    }
    return out;
  }
  return value;
}

/** Lower-case hex SHA-256 of a UTF-8 string, via Web Crypto (browsers and Node 20+). */
export async function sha256Hex(text: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
}

/** The state hash used by saves and by determinism checks (INV-14, INV-15). */
export const stateHash = (state: unknown): Promise<string> => sha256Hex(canonicalJson(state));
